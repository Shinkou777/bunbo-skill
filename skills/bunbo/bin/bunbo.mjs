var BY_LANG = { zh: ZH_BANS, ja: JA_BANS, en: EN_BANS };
function findBans(text, lang) {
  const hits = [];
  for (const re of BY_LANG[lang]) {
    const m = text.match(re);
    if (m && m[0] && !hits.includes(m[0])) hits.push(m[0]);
  }
  return hits;
}
function scanBans(obj, lang) {
  const out = [];
  const walk = (v) => {
    if (typeof v === "string") {
      for (const h of findBans(v, lang)) if (!out.includes(h)) out.push(h);
    } else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  walk(obj);
  return out;
}

