function walkStrings(v, path2, fn) {
  if (typeof v === "string") fn(v, path2);
  else if (Array.isArray(v)) v.forEach((x, i) => walkStrings(x, `${path2}[${i}]`, fn));
  else if (v && typeof v === "object")
    for (const [k, x] of Object.entries(v)) walkStrings(x, path2 ? `${path2}.${k}` : k, fn);
}
